use super::{Facts, render};

fn facts() -> Facts {
    Facts {
        slug: "o/r".into(),
        license: "MIT".into(),
        edition: "2024".into(),
        msrv: "1.95".into(),
        dependencies: 8,
        coverage: "97.3".into(),
        steps: (42, 51),
        spec: (300, 12, 29),
        nixpkgs: ("26.05".into(), "a033e66".into()),
        platforms: vec![("intel", "linux"), ("arm", "macos")],
    }
}

#[test]
fn alt_text_and_url_come_from_one_value() {
    let got = render(&facts());
    let steps = "[![gate steps 42 commit / 51 push](https://img.shields.io/badge/gate_steps-42_commit_%2F_51_push-6E4AFF)](hk.pkl)";
    assert!(got.contains(steps), "{got}");
    let cov = "line_coverage-97.3%25-brightgreen";
    assert!(got.contains(cov), "{got}");
    let nix = "[![nixpkgs 26.05 (a033e66)](https://img.shields.io/badge/nixpkgs-26.05_(a033e66)-";
    assert!(got.contains(nix), "{got}");
}

#[test]
fn the_block_has_its_markers_and_no_placeholder_left() {
    let got = render(&facts());
    assert!(got.starts_with("<!-- BEGIN badges: generated by"), "{got}");
    assert!(got.ends_with("<!-- END badges -->\n"), "{got}");
    assert!(!got.contains('{'), "{got}");
}

#[test]
fn one_badge_per_ci_platform() {
    let got = render(&facts());
    assert!(got.contains("badge/linux-intel-"), "{got}");
    assert!(got.contains("badge/macos-arm-"), "{got}");
    assert!(!got.contains("badge/linux-arm-"), "{got}");
}

#[test]
fn an_empty_or_zero_fact_is_refused_by_name() {
    assert!(facts().checked().is_ok());
    let mut f = facts();
    f.dependencies = 0;
    let err = f.checked().err().unwrap_or_default();
    assert!(err.contains("[dependencies]"), "{err}");
}
